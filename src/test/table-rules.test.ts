// @vitest-environment node
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

const admin = '00000000-0000-0000-0000-0000000000a1';
const user = '00000000-0000-0000-0000-0000000000b1';
const other = '00000000-0000-0000-0000-0000000000c1';
let db: PGlite;

const as = (uid: string) => db.query(`SELECT set_config('test.uid', '${uid}', false)`);

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`
    CREATE SCHEMA auth; CREATE ROLE authenticated NOLOGIN; CREATE ROLE anon NOLOGIN; CREATE ROLE service_role NOLOGIN;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('test.uid', true), '')::uuid $$;
    CREATE TABLE profiles(id uuid PRIMARY KEY, name text NOT NULL DEFAULT '', photo_url text, male boolean NOT NULL DEFAULT true,
      gold integer NOT NULL DEFAULT 100, kisses integer NOT NULL DEFAULT 0, vip_until timestamptz);
    CREATE TABLE user_roles(user_id uuid NOT NULL, role text NOT NULL);
    CREATE FUNCTION public.has_role(_user_id uuid, _role text) RETURNS boolean LANGUAGE sql STABLE AS
      $$ SELECT EXISTS (SELECT 1 FROM user_roles WHERE user_id = _user_id AND role = _role) $$;
    CREATE TABLE rooms(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phase text NOT NULL DEFAULT 'offer',
      spinner smallint, target smallint, decisions jsonb NOT NULL DEFAULT '{}', phase_at timestamptz NOT NULL DEFAULT now(),
      bottle text NOT NULL DEFAULT 'standart', music jsonb);
    CREATE TABLE room_players(room_id bigint NOT NULL, user_id uuid NOT NULL, seat smallint NOT NULL,
      kisses integer NOT NULL DEFAULT 0, joined_at timestamptz NOT NULL DEFAULT now(), last_seen timestamptz NOT NULL DEFAULT now(),
      CONSTRAINT room_players_seat_check CHECK (seat BETWEEN 0 AND 11));
    CREATE FUNCTION public.my_room() RETURNS bigint LANGUAGE sql STABLE AS
      $$ SELECT room_id FROM public.room_players WHERE user_id = auth.uid() $$;
    CREATE TABLE table_history(user_id uuid NOT NULL, room_id bigint NOT NULL, visited_at timestamptz NOT NULL DEFAULT now());
    CREATE TABLE kickout_targets(room_id bigint NOT NULL, user_id uuid NOT NULL, kicked_by uuid, blocked_until timestamptz);
    CREATE TABLE chat_messages(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, room_id bigint NOT NULL, user_id uuid NOT NULL,
      receiver_id uuid, text text NOT NULL, kind text NOT NULL DEFAULT 'chat', payload jsonb, created_at timestamptz NOT NULL DEFAULT now());
    CREATE TABLE bottle_prices(bottle text PRIMARY KEY, price integer NOT NULL, vip_only boolean NOT NULL DEFAULT false);
    INSERT INTO bottle_prices VALUES ('standart', 0, false), ('vipbottle', 5, true);
    CREATE TABLE gift_prices(gift_type text PRIMARY KEY, price integer NOT NULL, kisses_required integer NOT NULL DEFAULT 0, vip_only boolean NOT NULL DEFAULT false);
    INSERT INTO gift_prices VALUES ('rose', 1, 0, false);
    CREATE TABLE gift_events(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, room_id bigint NOT NULL, sender_id uuid NOT NULL,
      receiver_id uuid NOT NULL, gift_type text NOT NULL, seed integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now());
    CREATE TABLE dj_events(user_id uuid NOT NULL, points integer NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
    INSERT INTO profiles(id, name, male) VALUES ('${admin}', 'Admin', true), ('${user}', 'User', true), ('${other}', 'Other', false);
    INSERT INTO user_roles VALUES ('${admin}', 'admin');
    -- Room 1: full 12-seat table (6 men on odd seats, 6 women on even seats).
    INSERT INTO rooms(id, bottle) VALUES (1, 'standart'), (2, 'standart'), (3, 'standart');
    INSERT INTO room_players(room_id, user_id, seat)
      SELECT 1, gen_random_uuid(), g FROM generate_series(0, 11) g;`);
  await db.exec(readFileSync(new URL('../../drizzle/migrations/0042_table_rules.sql', import.meta.url), 'utf8'));
}, 30000);

afterAll(async () => { await db?.close(); });

describe('table rules (real game parity)', () => {
  it('lets an admin join a full 12-seat table as a spectator (seat -1)', async () => {
    await as(admin);
    const r = await db.query<{ room_id: number; seat: number }>(`SELECT * FROM public.change_table(1)`);
    expect(r.rows).toEqual([{ room_id: 1, seat: -1 }]);
    const n = await db.query<{ n: number }>(`SELECT count(*)::int n FROM room_players WHERE room_id = 1`);
    expect(n.rows[0]!.n).toBe(13);
  });

  it('rejects a non-admin from a full table with table_full', async () => {
    await as(user);
    await expect(db.query(`SELECT * FROM public.change_table(1)`)).rejects.toThrow('table_full');
  });

  it('hides empty tables from list_tables but keeps occupied and kickout-blocked ones', async () => {
    await as(user);
    await db.exec(`
      INSERT INTO room_players(room_id, user_id, seat) VALUES (2, '${user}', 1);
      INSERT INTO table_history VALUES ('${user}', 1, now()), ('${user}', 2, now()), ('${user}', 3, now());
      INSERT INTO kickout_targets VALUES (3, '${user}', '${admin}', now() + interval '1 hour');`);
    const r = await db.query<{ room_id: number; blocked_until: string | null }>(`SELECT * FROM public.list_tables()`);
    const ids = r.rows.map(x => Number(x.room_id));
    expect(ids).toContain(1); // full but occupied
    expect(ids).toContain(2); // current table
    expect(ids).toContain(3); // empty but kickout countdown active
    await db.exec(`DELETE FROM kickout_targets; INSERT INTO rooms(id) VALUES (4); INSERT INTO table_history VALUES ('${user}', 4, now())`);
    const r2 = await db.query<{ room_id: number }>(`SELECT * FROM public.list_tables()`);
    expect(r2.rows.map(x => Number(x.room_id))).not.toContain(4); // empty history table hidden
  });

  it('posts a bottle info line to the table chat when the bottle changes', async () => {
    await as(user);
    await db.query(`SELECT public.buy_bottle('standart')`);
    const r = await db.query<{ kind: string; payload: { old: string; new: string } }>(
      `SELECT kind, payload FROM chat_messages WHERE room_id = 2 ORDER BY id DESC LIMIT 1`);
    expect(r.rows[0]!.kind).toBe('bottle');
    expect(r.rows[0]!.payload).toEqual({ old: 'standart', new: 'standart' });
  });

  it('credits the receiver the gift kiss and heart rewards', async () => {
    await db.exec(`UPDATE gift_prices SET kisses = 2, hearts = 3 WHERE gift_type = 'rose'`);
    await as(user);
    await db.exec(`INSERT INTO room_players(room_id, user_id, seat) VALUES (2, '${other}', 2)`);
    const before = await db.query<{ kisses: number; gold: number }>(`SELECT kisses, gold FROM profiles WHERE id = '${other}'`);
    await db.query(`SELECT public.send_gift('rose', ARRAY['${other}']::uuid[], 0)`);
    const after = await db.query<{ kisses: number; gold: number }>(`SELECT kisses, gold FROM profiles WHERE id = '${other}'`);
    expect(after.rows[0]!.kisses - before.rows[0]!.kisses).toBe(2);
    expect(after.rows[0]!.gold - before.rows[0]!.gold).toBe(3);
    const seat = await db.query<{ kisses: number }>(`SELECT kisses FROM room_players WHERE room_id = 2 AND user_id = '${other}'`);
    expect(seat.rows[0]!.kisses).toBe(2);
  });
});

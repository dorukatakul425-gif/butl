// @vitest-environment node
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';

const a = '00000000-0000-0000-0000-000000000001';
const b = '00000000-0000-0000-0000-000000000002';
let db: PGlite;
const as = (id: string) => db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [id]);
const seatOf = async (id: string) => (await db.query<{ room_id: number; seat: number }>('SELECT room_id::int, seat::int FROM room_players WHERE user_id=$1', [id])).rows[0];
beforeAll(async () => {
  db = new PGlite();
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA auth; CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    CREATE TYPE app_role AS ENUM ('admin','user');
    CREATE TABLE user_roles(user_id uuid, role app_role);
    CREATE FUNCTION has_role(_user_id uuid,_role app_role) RETURNS boolean LANGUAGE sql AS $$ SELECT exists(SELECT 1 FROM user_roles WHERE user_id=_user_id AND role=_role) $$;
    CREATE TABLE profiles(id uuid PRIMARY KEY, male boolean NOT NULL);
    CREATE TABLE rooms(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, spinner smallint, phase_at timestamptz);
    CREATE TABLE room_players(room_id bigint REFERENCES rooms(id), seat smallint, user_id uuid PRIMARY KEY REFERENCES profiles(id), last_seen timestamptz DEFAULT now());
    CREATE TABLE chat_messages(id bigint PRIMARY KEY, text text);`);
  await db.exec(readFileSync(new URL('../../supabase/migrations/20261019130000_seat_restore_admin_chat_delete.sql', import.meta.url), 'utf8'));
}, 30000);
beforeEach(async () => {
  await db.exec(`TRUNCATE room_players, last_seats, profiles, rooms, chat_messages, user_roles CASCADE;
    INSERT INTO profiles VALUES('${a}', true),('${b}', true); INSERT INTO chat_messages VALUES(1,'hi');`);
  await as(a);
});
afterAll(async () => { await db?.close(); });
describe('seat after page reload', () => {
  it('returns the same table and seat when rejoining within 2 minutes', async () => {
    await db.query('SELECT * FROM join_room()'); const before = await seatOf(a);
    await db.query('SELECT leave_room()'); await db.query('SELECT * FROM join_room()');
    expect(await seatOf(a)).toEqual(before);
  });
  it('gives a new seat after 2 minutes away', async () => {
    await db.query('SELECT * FROM join_room()'); await db.query('SELECT leave_room()');
    await db.exec("UPDATE last_seats SET left_at = now() - interval '3 minutes'");
    await db.query('SELECT * FROM join_room()');
    expect((await db.query('SELECT * FROM last_seats')).rows).toHaveLength(1);
  });
});
describe('admin chat delete', () => {
  it('non-admins cannot delete messages', async () => {
    await expect(db.query('SELECT admin_delete_chat(1)')).rejects.toThrow('forbidden');
    expect((await db.query('SELECT * FROM chat_messages')).rows).toHaveLength(1);
  });
  it('admins delete the message', async () => {
    await db.exec(`INSERT INTO user_roles VALUES('${a}','admin')`);
    await db.query('SELECT admin_delete_chat(1)');
    expect((await db.query('SELECT * FROM chat_messages')).rows).toHaveLength(0);
  });
});

// @vitest-environment node
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

const sender = '00000000-0000-0000-0000-0000000000b1';
const receiver = '00000000-0000-0000-0000-0000000000c1';
let db: PGlite;

const as = (uid: string) => db.query(`SELECT set_config('test.uid', '${uid}', false)`);

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`
    CREATE SCHEMA auth; CREATE ROLE authenticated NOLOGIN; CREATE ROLE anon NOLOGIN; CREATE ROLE service_role NOLOGIN;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('test.uid', true), '')::uuid $$;
    CREATE TABLE profiles(id uuid PRIMARY KEY, name text NOT NULL DEFAULT '', photo_url text, male boolean NOT NULL DEFAULT true,
      gold integer NOT NULL DEFAULT 100, kisses integer NOT NULL DEFAULT 0, vip_until timestamptz);
    CREATE TABLE user_roles(user_id uuid NOT NULL, role text NOT NULL);
    CREATE FUNCTION public.has_role(_user_id uuid, _role text) RETURNS boolean LANGUAGE sql STABLE AS
      $$ SELECT EXISTS (SELECT 1 FROM user_roles WHERE user_id = _user_id AND role = _role) $$;
    CREATE TABLE rooms(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phase text NOT NULL DEFAULT 'offer',
      spinner smallint, target smallint, decisions jsonb NOT NULL DEFAULT '{}', phase_at timestamptz NOT NULL DEFAULT now(),
      bottle text NOT NULL DEFAULT 'standart', music jsonb);
    CREATE TABLE room_players(room_id bigint NOT NULL, user_id uuid NOT NULL, seat smallint NOT NULL,
      kisses integer NOT NULL DEFAULT 0, joined_at timestamptz NOT NULL DEFAULT now(), last_seen timestamptz NOT NULL DEFAULT now(),
      CONSTRAINT room_players_seat_check CHECK (seat BETWEEN 0 AND 11));
    CREATE FUNCTION public.my_room() RETURNS bigint LANGUAGE sql STABLE AS
      $$ SELECT room_id FROM public.room_players WHERE user_id = auth.uid() $$;
    CREATE TABLE table_history(user_id uuid NOT NULL, room_id bigint NOT NULL, visited_at timestamptz NOT NULL DEFAULT now());
    CREATE TABLE kickout_targets(room_id bigint NOT NULL, user_id uuid NOT NULL, kicked_by uuid, blocked_until timestamptz);
    CREATE TABLE chat_messages(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, room_id bigint NOT NULL, user_id uuid NOT NULL,
      receiver_id uuid, text text NOT NULL, kind text NOT NULL DEFAULT 'chat', payload jsonb, created_at timestamptz NOT NULL DEFAULT now());
    CREATE TABLE bottle_prices(bottle text PRIMARY KEY, price integer NOT NULL, vip_only boolean NOT NULL DEFAULT false);
    CREATE TABLE gift_prices(gift_type text PRIMARY KEY, price integer NOT NULL, kisses_required integer NOT NULL DEFAULT 0, vip_only boolean NOT NULL DEFAULT false);
    INSERT INTO gift_prices VALUES ('rose', 1, 0, false), ('vodka', 3, 0, false), ('ushanka', 2, 0, false);
    CREATE TABLE gift_events(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, room_id bigint NOT NULL, sender_id uuid NOT NULL,
      receiver_id uuid NOT NULL, gift_type text NOT NULL, seed integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now());
    CREATE TABLE dj_events(user_id uuid NOT NULL, points integer NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
    INSERT INTO profiles(id, name, male) VALUES ('${sender}', 'Sender', true), ('${receiver}', 'Receiver', false);
    INSERT INTO rooms(id) VALUES (1);
    INSERT INTO room_players(room_id, user_id, seat) VALUES (1, '${sender}', 1), (1, '${receiver}', 2);`);
  await db.exec(readFileSync(new URL('../../drizzle/migrations/0042_table_rules.sql', import.meta.url), 'utf8'));
  await db.exec(readFileSync(new URL('../../drizzle/migrations/0043_gift_receiver_effect.sql', import.meta.url), 'utf8'));
}, 30000);

afterAll(async () => { await db?.close(); });

describe('gift receiver effect (real game parity)', () => {
  it('gives every placeholder gift a kiss payout equal to its heart price', async () => {
    const r = await db.query<{ gift_type: string; price: number; kisses: number }>(
      `SELECT gift_type, price, kisses FROM gift_prices ORDER BY gift_type`);
    for (const row of r.rows) expect(row.kisses).toBe(row.price);
  });

  it('sending a gift raises the receiver profile and table kiss counters by the gift price', async () => {
    await as(sender);
    await db.query(`SELECT public.send_gift('vodka', ARRAY['${receiver}']::uuid[], 0)`);
    const p = await db.query<{ kisses: number }>(`SELECT kisses FROM profiles WHERE id = '${receiver}'`);
    expect(p.rows[0]!.kisses).toBe(3);
    const rp = await db.query<{ kisses: number }>(`SELECT kisses FROM room_players WHERE room_id = 1 AND user_id = '${receiver}'`);
    expect(rp.rows[0]!.kisses).toBe(3);
  });

  it('the sender gains no kisses from their own gift', async () => {
    await as(sender);
    await db.query(`SELECT public.send_gift('rose', ARRAY['${receiver}']::uuid[], 0)`);
    const p = await db.query<{ kisses: number }>(`SELECT kisses FROM profiles WHERE id = '${sender}'`);
    expect(p.rows[0]!.kisses).toBe(0);
  });
});
